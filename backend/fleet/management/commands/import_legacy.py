"""Import vehicles from the old AdyBajaj Firebase app.

Input: a JSON file shaped like {"vehicles": [ {...}, ... ]} where each vehicle has the old
field names (name, type, dailyTarget, workingDays, driverName, driverPhone, includeWeek5,
manualDaysLost, returns, debtHistory, carryOverDebt). Use the dump script in tools/.

The old weekly debt rows are NOT copied. They are regenerated by the new engine. Only manual
entries are copied. The command then compares the new ending debt with the old one for each
month and prints the differences. Differences in months the old app skipped are expected.
"""
import json
from datetime import date
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from fleet.models import Vehicle, DriverPeriod, Return, LostDays, ManualLedgerEntry
from fleet.services import vehicle_debt

MANUAL_KINDS = {"MANUAL_DEBT", "MANUAL_PAYMENT", "CARRY_OVER"}


def _d(s):
    return date.fromisoformat(str(s)[:10])


def _month(d):
    return f"{d.year:04d}-{d.month:02d}"


class Command(BaseCommand):
    help = "Import vehicles from the old Firebase app JSON export"

    def add_arguments(self, parser):
        parser.add_argument("path")
        parser.add_argument("--owner", required=True, help="username that will own the imported vehicles")

    def handle(self, *args, **opts):
        try:
            owner = get_user_model().objects.get(username=opts["owner"])
        except get_user_model().DoesNotExist:
            raise CommandError(f"No user named {opts['owner']}")
        with open(opts["path"], encoding="utf-8") as f:
            data = json.load(f)

        with transaction.atomic():
            for legacy in data.get("vehicles", []):
                self.import_vehicle(owner, legacy)

        self.stdout.write(self.style.SUCCESS("Import finished. Check the comparison above."))

    def import_vehicle(self, owner, old):
        legacy_id = str(old.get("id", ""))
        if Vehicle.objects.filter(owner=owner, legacy_id=legacy_id).exists():
            self.stdout.write(f"Skipping {old.get('name')}: already imported")
            return
        working = old.get("workingDays") or [1, 2, 3, 4, 5, 6]
        vehicle = Vehicle.objects.create(
            owner=owner, name=str(old.get("name", "")).upper()[:32], legacy_id=legacy_id,
            vehicle_type=old.get("type", "Bajaj"), daily_target=int(old.get("dailyTarget", 16000)),
            working_days_count=len(working) or 6, include_week5=bool(old.get("includeWeek5", False)))

        if old.get("driverName"):
            DriverPeriod.objects.create(vehicle=vehicle, driver_name=old["driverName"],
                                        phone=old.get("driverPhone", ""), from_date=date(1900, 1, 1))

        for month, weeks in (old.get("manualDaysLost") or {}).items():
            for week, days in (weeks or {}).items():
                if int(days or 0) > 0:
                    LostDays.objects.create(vehicle=vehicle, month=month, week_number=int(week), days=int(days))

        for r in old.get("returns") or []:
            if not r.get("date") or not r.get("amount"):
                continue
            Return.objects.create(vehicle=vehicle, day=_d(r["date"]), amount=int(r["amount"]),
                                  is_excess=bool(r.get("isExcess", False)))

        for e in old.get("debtHistory") or []:
            kind = e.get("type")
            if kind not in MANUAL_KINDS and not e.get("sourceRecordId"):
                continue  # weekly rows are regenerated
            if kind == "MANUAL_PAYMENT" or (kind not in MANUAL_KINDS and float(e.get("paidDebt") or 0) > 0):
                mk, amount = "MANUAL_PAYMENT", int(e.get("paidDebt") or 0)
            else:
                mk, amount = (kind if kind in MANUAL_KINDS else "MANUAL_DEBT"), int(e.get("newDebt") or 0)
            if amount <= 0 or not e.get("date"):
                continue
            ManualLedgerEntry.objects.create(vehicle=vehicle, kind=mk, day=_d(e["date"]),
                                             amount=amount, note=str(e.get("notes", ""))[:200])

        if float(old.get("carryOverDebt") or 0) > 0 and not vehicle.manual_entries.filter(kind="CARRY_OVER").exists():
            first = min([_d(r["date"]) for r in old.get("returns") or [] if r.get("date")] or [date(2025, 1, 1)])
            ManualLedgerEntry.objects.create(vehicle=vehicle, kind="CARRY_OVER", day=first.replace(day=1),
                                             amount=int(old["carryOverDebt"]),
                                             note="Imeletwa kutoka carryOverDebt ya app ya zamani")
            self.stdout.write(self.style.WARNING(
                f"{vehicle.name}: carryOverDebt {old['carryOverDebt']} added as opening CARRY_OVER. "
                "Check that it is not counted twice."))

        self.compare(vehicle, old)

    def compare(self, vehicle, old):
        """Print old vs new ending debt for each month the old app recorded."""
        last_old = {}
        for e in sorted(old.get("debtHistory") or [], key=lambda e: (e.get("month", ""), str(e.get("date", "")))):
            if e.get("month") and e.get("remainingDebt") is not None:
                last_old[e["month"]] = float(e["remainingDebt"])
        if not last_old:
            return
        end = max(last_old)
        entries = vehicle_debt(vehicle, end)
        new_end = {}
        for e in entries:
            new_end[e.month] = e.remaining_debt
        self.stdout.write(f"\n{vehicle.name}: month | old app | new engine | diff")
        for m in sorted(last_old):
            new = new_end.get(m, 0)
            diff = new - last_old[m]
            flag = "" if abs(diff) < 1 else "  <-- check"
            self.stdout.write(f"  {m} | {last_old[m]:>12,.0f} | {new:>12,.0f} | {diff:>12,.0f}{flag}")
